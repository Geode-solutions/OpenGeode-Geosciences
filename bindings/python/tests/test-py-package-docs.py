"""The documentation of the package (help(opengeode_geosciences)) stays
correct: the examples are executed as doctests, every module has a docstring,
and the generated __init__.py of the wheel carries the same text.

Arguments: the text file of the documentation, the wheel package directory
generated by CMake."""

import ast
import doctest
import io
import os
import sys

import geode_test_env

import opengeode


def check(condition, message):
    if not condition:
        raise ValueError("[Test] " + message)


def run_examples(documentation):
    parser = doctest.DocTestParser()
    test = parser.get_doctest(documentation, {}, "opengeode_geosciences", None, 0)
    check(len(test.examples) >= 10, f"Only {len(test.examples)} examples")
    output = io.StringIO()
    runner = doctest.DocTestRunner(verbose=False, optionflags=doctest.ELLIPSIS)
    runner.run(test, out=output.write)
    results = runner.summarize(verbose=False)
    check(results.failed == 0, f"{results.failed} example(s) failed:\n{output.getvalue()}")


def check_docstrings(documentation):
    import opengeode_geosciences
    import opengeode_geosciences_py_explicit
    import opengeode_geosciences_py_implicit
    import opengeode_geosciences_py_simulation
    import explicit
    import implicit
    import simulation

    check(opengeode_geosciences.__doc__ == documentation, "Wrong __doc__")
    for module in [
        explicit,
        implicit,
        simulation,
        opengeode_geosciences_py_explicit,
        opengeode_geosciences_py_implicit,
        opengeode_geosciences_py_simulation,
    ]:
        check(
            module.__doc__ and len(module.__doc__) > 40,
            f"No docstring in {module.__name__}",
        )
    for module, name in [
        (opengeode_geosciences_py_explicit, "OpenGeodeGeosciencesExplicitLibrary"),
        (opengeode_geosciences_py_implicit, "OpenGeodeGeosciencesImplicitLibrary"),
        (opengeode_geosciences_py_simulation, "OpenGeodeGeosciencesSimulationLibrary"),
    ]:
        library = getattr(module, name)
        check(library.__doc__, f"No docstring for {name}")
        check(library.initialize.__doc__, f"No docstring for {name}.initialize")
        # No instance is needed: initialize is called on the class, twice
        library.initialize()
        library.initialize()


def check_implicit_imports():
    """The claims of the implicit module docstring about what it imports"""
    import subprocess

    script = (
        "import sys, geode_test_env, implicit; "
        "print('opengeode_geosciences_py_explicit' in sys.modules, "
        "'explicit' in sys.modules)"
    )
    result = subprocess.run(
        [sys.executable, "-c", script], capture_output=True, text=True, check=True
    )
    check(
        result.stdout.split() == ["True", "False"],
        "implicit should import the explicit extension module only: "
        + result.stdout
        + result.stderr,
    )
    import implicit

    check(
        "explicit extension module" in implicit.__doc__
        and "only imported with the package" in implicit.__doc__,
        "Wrong implicit imports docstring: " + implicit.__doc__,
    )


def check_wheel_init(documentation, wheel_directory):
    init = os.path.join(wheel_directory, "__init__.py")
    with open(init, encoding="utf-8") as file:
        content = file.read()
    check(
        ast.get_docstring(ast.parse(content), clean=False) == documentation,
        "Wrong __init__.py docstring",
    )
    for name in ["explicit", "implicit", "simulation"]:
        path = os.path.join(wheel_directory, name + ".py")
        with open(path, encoding="utf-8") as file:
            module = ast.parse(file.read())
        check(ast.get_docstring(module), f"No docstring in the wheel {name}.py")


if __name__ == "__main__":
    with open(sys.argv[1], encoding="utf-8") as file:
        documentation = file.read()
    run_examples(documentation)
    check_docstrings(documentation)
    check_implicit_imports()
    check_wheel_init(documentation, sys.argv[2])
